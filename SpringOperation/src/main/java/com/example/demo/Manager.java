package com.example.demo;

public class Manager {
   String Id;
   String Room;
   Float salary;
   public String getId() {
	return Id;
   }
   public void setId(String id) {
	Id = id;
   }
   public String getRoom() {
	return Room;
   }
   public void setRoom(String room) {
	Room = room;
   }
   public Float getSalary() {
	return salary;
   }
   public void setSalary(Float salary) {
	this.salary = salary;
   }
   
}
